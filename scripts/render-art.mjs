// Renders the mod's art to SVG files, for a look or a screenshot, from the
// same functions the panes draw with:
//
//   node scripts/render-art.mjs [out-dir]   (default: ./art-out, not committed)
//   node scripts/render-art.mjs --snapshot  (writes tests/fixtures/scroll-snapshot.ts and hud-snapshot.ts)
//
// Writes the Quest Board's header and its cards (rolled and unrolled), a
// board page as HTML (the cards stacked as the desktop pane stacks them), the
// Scene for each kind of Encounter, the Boss Fight, the Sage's portrait and
// the HUD's pixel strip at a few band widths.
// Node runs the TypeScript sources itself (type stripping, Node 23.6+); the
// hooks below let their extensionless imports (`./sprites`) resolve, and
// compile a .tsx source's JSX (src/hud.tsx) with the project's TypeScript.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { registerHooks } from 'node:module'
import { fileURLToPath } from 'node:url'

import ts from 'typescript'

registerHooks({
  load: (url, context, next) => {
    if (!url.endsWith('.tsx')) {
      return next(url, context)
    }
    const { outputText } = ts.transpileModule(readFileSync(fileURLToPath(url), 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2023, jsx: ts.JsxEmit.React, jsxFactory: 'h' },
    })

    return { format: 'module', source: outputText, shortCircuit: true }
  },
  resolve: (specifier, context, next) => {
    try {
      return next(specifier, context)
    } catch (error) {
      if (!specifier.startsWith('.')) {
        throw error
      }

      try {
        return next(`${specifier}.ts`, context)
      } catch {
        return next(`${specifier}.tsx`, context)
      }
    }
  },
})

const { boardHeaderSvg, scrollCardSvg, SCROLL_WIDTH } = await import('../src/scroll-art.ts')
const { bossSceneSvg, portraitSvg, sceneSvg } = await import('../src/scene-art.ts')
const { SAMPLE_CARDS, SAMPLE_SELECTED, SAMPLE_XP } = await import('../tests/fixtures/quest-cards.ts')
const { hudStrip, PIXELS_PER_COLUMN } = await import('../src/hud-art.ts')
const { stripOf } = await import('../src/hud.tsx')
const { HUD_BATTLE, HUD_CALM, HUD_WORST, playerAt } = await import('../tests/fixtures/hud-states.ts')

// The HUD's strip, as the desktop draws it for a band so many columns wide.
const strip = (state, columns, motion) => hudStrip(stripOf(state, columns), columns * PIXELS_PER_COLUMN, motion).svg

/** The games the strip's snapshot is drawn for: with and without a Quest, a boss, Questions waiting and Exhausted. */
const HUD_SAMPLES = { worst: HUD_WORST, calm: HUD_CALM, battle: HUD_BATTLE }

// The scroll art's snapshot: the sample board's header and cards, which
// tests/scroll-art.test.ts compares the art with. Written again, after a
// look, when the art changes on purpose.
if (process.argv[2] === '--snapshot') {
  const cards = SAMPLE_CARDS.map(card =>
    scrollCardSvg(card, { unrolled: card.ticket === SAMPLE_SELECTED, xp: SAMPLE_XP[card.difficulty] }),
  )
  writeFileSync(
    new URL('../tests/fixtures/scroll-snapshot.ts', import.meta.url),
    `// Generated by scripts/render-art.mjs --snapshot: the scroll art of the sample
// board (tests/fixtures/quest-cards.ts), as approved by eye. Do not edit.

export const HEADER_SNAPSHOT = ${JSON.stringify(boardHeaderSvg('QUEST BOARD'))}

export const CARD_SNAPSHOTS = [
${cards.map(svg => `  ${JSON.stringify(svg)},`).join('\n')}
]
`,
  )
  console.log('tests/fixtures/scroll-snapshot.ts')
  writeFileSync(
    new URL('../tests/fixtures/hud-snapshot.ts', import.meta.url),
    `// Generated by scripts/render-art.mjs --snapshot: the HUD's pixel strip for
// the sample games (tests/fixtures/hud-states.ts) at 200 columns, as approved
// by eye. Do not edit.

export const HUD_SNAPSHOTS = ${JSON.stringify(Object.fromEntries(Object.entries(HUD_SAMPLES).map(([name, state]) => [name, strip(state, 200)])), null, 2)}
`,
  )
  console.log('tests/fixtures/hud-snapshot.ts')
  process.exit(0)
}

const out = process.argv[2] ?? 'art-out'
mkdirSync(out, { recursive: true })
const write = (name, svg) => {
  writeFileSync(`${out}/${name}`, svg)
  console.log(`${name}: ${svg.length} chars`)
}

const header = boardHeaderSvg('QUEST BOARD')
write('board-header.svg', header)
const cards = SAMPLE_CARDS.map((card, at) => {
  const unrolled = card.ticket === SAMPLE_SELECTED
  const svg = scrollCardSvg(card, { unrolled, xp: SAMPLE_XP[card.difficulty] })
  write(`card-${at}-${unrolled ? 'unrolled' : 'rolled'}.svg`, svg)
  write(`card-${at}-${unrolled ? 'rolled' : 'unrolled'}.svg`, scrollCardSvg(card, { unrolled: !unrolled, xp: SAMPLE_XP[card.difficulty] }))

  return { card, svg, unrolled }
})
// Each SVG in its own <img>, as the surface isolates each Svg element.
const img = svg => `<img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}">`
writeFileSync(
  `${out}/board.html`,
  `<!doctype html><meta charset="utf-8"><title>Quest Board</title>
<style>body{background:#2b2b33;color:#ddd;font:13px system-ui;margin:16px;width:${SCROLL_WIDTH + 16}px}img{display:block}
.row{display:flex;gap:6px;margin:4px 0 10px}button{font:12px system-ui;padding:3px 10px;border-radius:5px;border:1px solid #666;background:#3a3a44;color:#eee}
button.primary{background:#3a7bd5;border-color:#3a7bd5}</style>
<div>Trophies 1 · ★3</div><div class="row"><button>Status: all</button><button>Difficulty: all</button><button>Refresh</button></div>
${img(header)}<p>${cards.length} of ${cards.length} Quests</p>
${cards.map(({ card, svg, unrolled }) => `${img(svg)}<div class="row"><button class="primary">Take Quest ${card.ticket}</button><button>${unrolled ? 'Roll up' : 'Unroll'}</button></div>`).join('\n')}
`,
)
console.log('board.html')

const T = Date.UTC(2026, 9, 24)
write('scene-idle.svg', sceneSvg(null, 384))
write('scene-exploration.svg', sceneSvg({ kind: 'Exploration', target: 'src/engine.ts', module: 'src', isFirstVisit: true, xp: 6, discoveryXp: 5, at: T }, 384))
write('scene-battle.svg', sceneSvg({ kind: 'Battle', foe: 'test', check: 'vitest run', outcome: 'hit', hp: 2, maxHp: 4, hits: 2, isCounted: true, at: T }, 384))
write('scene-crafting.svg', sceneSvg({ kind: 'Crafting', target: 'src/order-ledger.ts', module: 'src', item: 'Order Ledger', isNewFile: true, linesAdded: 40, linesRemoved: 0, at: T }, 384))
write('scene-boss.svg', bossSceneSvg({ ticket: '#12', status: 'fighting', hp: 1, maxHp: 2, questions: [], lastAnswer: { isCorrect: true, hpLost: 0 }, questionCount: 3, rightAnswers: 1 }, 384))
write('portrait-sage.svg', portraitSvg('sage', 96))
write('portrait-boss.svg', portraitSvg('boss', 96))

for (const columns of [40, 80, 120, 200]) {
  write(`hud-worst-${columns}.svg`, strip(HUD_WORST, columns))
}
write('hud-calm-80.svg', strip(HUD_CALM, 80))
write('hud-calm-200.svg', strip(HUD_CALM, 200))
write('hud-battle-200.svg', strip(HUD_BATTLE, 200))
for (const [name, stats] of [['adventurer', {}], ['scholar', { intelligence: 9 }], ['pathfinder', { wisdom: 9 }], ['warrior', { strength: 9 }]]) {
  write(`hud-portrait-${name}.svg`, strip({ ...HUD_CALM, player: { ...playerAt(name === 'adventurer' ? 2 : 3, stats) } }, 80))
}

